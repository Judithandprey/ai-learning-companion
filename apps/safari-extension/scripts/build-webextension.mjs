#!/usr/bin/env node
// Builds webextension/content.js: the content script of the WebExtension entry, as ONE classic
// script (content scripts cannot be ES modules in Safari or when injected by scripting.executeScript).
//
// Compiles the module with the lead's pinned TypeScript into a temporary directory, follows the
// entry's relative imports, and wraps each compiled module in a function inside one IIFE. It works
// line by line on the forms tsc emits for these sources (named imports; single-name
// `export function|class|const` declarations). Other import/export forms at the start of a line stop
// the build. It does not parse JavaScript, so it cannot see export-like lines inside template
// literals; keep such text out of the entry's modules. No dependency is added.
//
// Usage: node scripts/build-webextension.mjs [--check]
//   --check  fail (exit 1) if the committed webextension/content.js differs from a fresh build.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MODULE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(MODULE, '..', '..');
const ENTRY = 'apps/safari-extension/src/extension-content.js';
const OUT = join(MODULE, 'webextension', 'content.js');
const TSC = process.env.TSC ?? join(process.env.LC_LEAD_REPO ?? '/home/agentsdock/Projects/learning-companion/repo', 'node_modules', 'typescript', 'bin', 'tsc');

const IMPORT = /^import \{([^}]*)\} from '(\.{1,2}\/[^']+)';$/;
const SIDE_EFFECT_IMPORT = /^import '(\.{1,2}\/[^']+)';$/;
const EXPORT_DECLARATION = /^export ((?:async )?function\*? ([A-Za-z_$][\w$]*)|class ([A-Za-z_$][\w$]*)|const ([A-Za-z_$][\w$]*) )/;

/** Rewrites one compiled module into the body of a factory `(exports, require) => { ... }`. */
function transform(id, source) {
  const deps = [];
  const exported = [];
  const lines = source.split('\n').map((text, i) => {
    const where = `${id}:${i + 1}`;
    let m = IMPORT.exec(text);
    if (m) {
      const dep = join(dirname(id), m[2]);
      deps.push(dep);
      const names = m[1]
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => {
          const parts = s.split(/\s+as\s+/);
          if (parts.length > 2 || parts.some((p) => !/^[A-Za-z_$][\w$]*$/.test(p))) throw new Error(`unsupported import specifier "${s}" at ${where}`);
          return parts.length === 2 ? `${parts[0]}: ${parts[1]}` : parts[0];
        });
      return `const { ${names.join(', ')} } = require(${JSON.stringify(dep)});`;
    }
    m = SIDE_EFFECT_IMPORT.exec(text);
    if (m) {
      const dep = join(dirname(id), m[1]);
      deps.push(dep);
      return `require(${JSON.stringify(dep)});`;
    }
    if (/^\s*import[\s{*'"(]/.test(text) || /\bimport\.meta\b/.test(text)) throw new Error(`unsupported import form at ${where}: ${text.trim()}`);
    m = EXPORT_DECLARATION.exec(text);
    if (m && /^export const [A-Za-z_$][\w$]*\s*=[^;]*,\s*[A-Za-z_$][\w$]*\s*=/.test(text)) throw new Error(`unsupported multi-name export at ${where}`);
    if (m) {
      exported.push(m[2] ?? m[3] ?? m[4]);
      return text.slice('export '.length);
    }
    if (/^export\b/.test(text)) throw new Error(`unsupported export form at ${where}: ${text.trim()}`);
    return text;
  });
  const body = [...lines, ...exported.map((name) => `exports.${name} = ${name};`)].join('\n');
  return { deps, body };
}

function bundle(outDir) {
  const modules = new Map();
  const order = [];
  const visiting = new Set();
  const visit = (id, from) => {
    if (modules.has(id)) return;
    if (visiting.has(id)) throw new Error(`import cycle through ${id} (from ${from})`);
    const file = join(outDir, id);
    if (!existsSync(file)) throw new Error(`missing compiled module ${id} (imported by ${from})`);
    visiting.add(id);
    const mod = transform(id, readFileSync(file, 'utf8'));
    for (const dep of mod.deps) visit(dep, id);
    visiting.delete(id);
    modules.set(id, mod);
    order.push(id);
  };
  visit(ENTRY, 'the entry');
  const parts = [
    '// GENERATED by apps/safari-extension/scripts/build-webextension.mjs from apps/safari-extension/src.',
    '// Do not edit: change the TypeScript sources and rebuild (check with --check).',
    `// Modules (dependency order): ${order.map((id) => relative('apps/safari-extension', id)).join(', ')}`,
    '(() => {',
    "'use strict';",
    'const factories = new Map();',
    'const cache = new Map();',
    'const require = (id) => {',
    '  if (cache.has(id)) return cache.get(id);',
    '  const exports = {};',
    '  cache.set(id, exports);',
    '  factories.get(id)(exports, require);',
    '  return exports;',
    '};',
  ];
  for (const id of order) parts.push(`factories.set(${JSON.stringify(id)}, (exports, require) => {`, modules.get(id).body, '});');
  parts.push(`require(${JSON.stringify(ENTRY)});`, '})();', '');
  return parts.join('\n');
}

const check = process.argv.includes('--check');
const outDir = mkdtempSync(join(tmpdir(), 'lc-webextension-'));
try {
  execFileSync(process.execPath, [TSC, '-p', join(MODULE, 'tsconfig.build.json'), '--outDir', outDir], { cwd: MODULE, stdio: 'inherit' });
  const built = bundle(outDir);
  if (check) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== built) {
      console.error(`${relative(ROOT, OUT)} is not current: run node apps/safari-extension/scripts/build-webextension.mjs`);
      process.exitCode = 1;
    } else {
      console.log(`${relative(ROOT, OUT)} is current`);
    }
  } else {
    writeFileSync(OUT, built);
    console.log(`wrote ${relative(ROOT, OUT)} (${Buffer.byteLength(built)} bytes)`);
  }
} finally {
  rmSync(outDir, { recursive: true, force: true });
}
